import zipfile, glob, os
zips = glob.glob('/content/*.zip')
print('Zip files found:', zips)
assert zips, 'No zip found in /content - upload it first!'
for z in zips:
    if not zipfile.is_zipfile(z):
        print(f"Warning: '{z}' exists but is NOT a valid zip file. Please make sure it finished uploading or re-upload a non-corrupted version.")
    else:
        with zipfile.ZipFile(z, 'r') as f:
            f.extractall('/content/data')
for p in glob.glob('/content/data/**/*', recursive=True)[:20]:
    print(p)

"""## 2. Imports"""

import numpy as np, pandas as pd, matplotlib.pyplot as plt, time
import tensorflow as tf
from sklearn.model_selection import train_test_split
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, LSTM, Bidirectional, Conv1D, GlobalMaxPooling1D, Dense, Dropout
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences
print('TF', tf.__version__, '| GPU:', tf.config.list_physical_devices('GPU'))

"""## 3. Load dataset (auto-detects text & label columns)"""

csvs = glob.glob('/content/data/**/*.csv', recursive=True) + glob.glob('/content/data/**/*.tsv', recursive=True)
assert csvs, 'No CSV/TSV found inside the zip'
path = max(csvs, key=os.path.getsize)
print('Using file:', path)

sep = '\t' if path.endswith('.tsv') else ','
try:
    df = pd.read_csv(path, sep=sep)
except UnicodeDecodeError:
    df = pd.read_csv(path, sep=sep, encoding='latin-1')

df = df.dropna(axis=1, thresh=int(len(df) * 0.5)).dropna().reset_index(drop=True)  # drop junk columns/rows
print(df.shape); display(df.head())

obj_cols = [c for c in df.columns if df[c].dtype == object]
TEXT_COL = max(obj_cols, key=lambda c: df[c].astype(str).str.len().mean())
LABEL_COL = [c for c in df.columns if c != TEXT_COL and df[c].nunique() == 2][0]
print('Text column :', TEXT_COL, '| Label column:', LABEL_COL)

# OPTIONAL: speed-up for big datasets (set None to use everything)
MAX_SAMPLES = 25000
if MAX_SAMPLES and len(df) > MAX_SAMPLES:
    df = df.sample(MAX_SAMPLES, random_state=42).reset_index(drop=True)

# Encode labels to 0/1
if pd.api.types.is_numeric_dtype(df[LABEL_COL]):
    y = df[LABEL_COL].astype(int).values
else:
    classes = sorted(df[LABEL_COL].unique())
    mapping = {c: i for i, c in enumerate(classes)}
    print('Label mapping:', mapping)
    y = df[LABEL_COL].map(mapping).values
print('Class balance:', np.bincount(y))
texts = df[TEXT_COL].astype(str).values

"""## 4. Preprocess (tokenize + pad)"""

VOCAB, MAXLEN = 5000, 200
X_tr_txt, X_te_txt, y_train, y_test = train_test_split(texts, y, test_size=0.2, random_state=42, stratify=y)

tokenizer = Tokenizer(num_words=VOCAB)
tokenizer.fit_on_texts(X_tr_txt)                      # fit ONLY on train
X_train = pad_sequences(tokenizer.texts_to_sequences(X_tr_txt), maxlen=MAXLEN)
X_test  = pad_sequences(tokenizer.texts_to_sequences(X_te_txt), maxlen=MAXLEN)
print(X_train.shape, X_test.shape)

"""## 5. Three models, configurable hidden layers
- **LSTM** - same as the video (cuDNN-friendly, so it trains fast on GPU)
- **Bi-LSTM** - reads the text forward and backward
- **1D-CNN** - Conv1D + max pooling (very fast, good baseline)
"""

def build_model(kind, n_layers, units=64):
    m = Sequential([Embedding(VOCAB, 128, input_length=MAXLEN)])
    if kind in ('LSTM', 'BiLSTM'):
        for i in range(n_layers):
            last = (i == n_layers - 1)
            layer = LSTM(units, return_sequences=not last)
            m.add(Bidirectional(layer) if kind == 'BiLSTM' else layer)
            m.add(Dropout(0.3))
    else:  # CNN
        for i in range(n_layers):
            m.add(Conv1D(units, 5, activation='relu'))
        m.add(GlobalMaxPooling1D())
        m.add(Dropout(0.3))
    m.add(Dense(1, activation='sigmoid'))
    m.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
    return m

class TestAcc(tf.keras.callbacks.Callback):
    # records test accuracy after every epoch, so we can compare 1..N epochs without retraining
    def __init__(self): super().__init__(); self.accs = []
    def on_epoch_end(self, epoch, logs=None):
        self.accs.append(self.model.evaluate(X_test, y_test, verbose=0)[1])

build_model('LSTM', 1).summary()

"""## 6. Run experiments (3 models x 2 depths x 5 epochs)
Takes roughly 10-25 min on a T4 GPU.
"""

EPOCHS, BATCH = 5, 128
MODELS, LAYERS = ['LSTM', 'BiLSTM', 'CNN'], [1, 2]

rows, trained = [], {}
for kind in MODELS:
    for nl in LAYERS:
        print(f'\n=== {kind} | hidden layers = {nl} ===')
        m = build_model(kind, nl)
        cb = TestAcc()
        t0 = time.time()
        m.fit(X_train, y_train, epochs=EPOCHS, batch_size=BATCH, validation_split=0.2, callbacks=[cb], verbose=2)
        secs = time.time() - t0
        for ep, acc in enumerate(cb.accs, 1):
            rows.append(dict(Model=kind, Layers=nl, Epochs=ep, TestAcc=round(acc, 4), TrainTime_s=round(secs, 1)))
        trained[(kind, nl)] = m

results = pd.DataFrame(rows)
display(results.pivot_table(index=['Model', 'Layers'], columns='Epochs', values='TestAcc'))

"""## 7. Compare & pick the best"""

fig, axes = plt.subplots(1, 2, figsize=(14, 5))
for (kind, nl), g in results.groupby(['Model', 'Layers']):
    axes[0].plot(g['Epochs'], g['TestAcc'], marker='o', label=f'{kind} - {nl} layer(s)')
axes[0].set_xlabel('Epochs'); axes[0].set_ylabel('Test accuracy'); axes[0].set_title('Accuracy vs Epochs'); axes[0].legend(); axes[0].grid(alpha=.3)

final = results[results.Epochs == EPOCHS]
labels = [f'{r.Model}-{r.Layers}L' for r in final.itertuples()]
axes[1].bar(labels, final['TestAcc'])
axes[1].set_ylim(final['TestAcc'].min() - 0.03, final['TestAcc'].max() + 0.02)
axes[1].set_title(f'Test accuracy after {EPOCHS} epochs'); plt.xticks(rotation=30)
plt.tight_layout(); plt.show()

best = results.loc[results['TestAcc'].idxmax()]
print('BEST CONFIG ->', dict(best))
display(results.sort_values('TestAcc', ascending=False).head(5))

"""## 8. Predict on your own text (with the best model)"""

best_model = trained[(best.Model, int(best.Layers))]

def predict(text):
    seq = tokenizer.texts_to_sequences([text])          # NOTE: list -> single data point
    pad = pad_sequences(seq, maxlen=MAXLEN)
    p = float(best_model.predict(pad, verbose=0)[0][0])
    return ('class 1' if p > 0.5 else 'class 0'), round(p, 3)

for s in ['This movie was fantastic, I loved it',
          'This movie was not that good',
          'Congratulations! You won a free prize, click now']:
    print(s, '->', predict(s))

"""## 9. Save the best model"""

import pickle
best_model.save('best_model.keras')
pickle.dump(tokenizer, open('tokenizer.pkl', 'wb'))
results.to_csv('results.csv', index=False)
print('Saved: best_model.keras, tokenizer.pkl, results.csv')

